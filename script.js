const cardsGrid = document.getElementById('cardsGrid');
const searchInput = document.getElementById('searchInput');
const clearBtn = document.getElementById('clearSearch');
const filterBtns = document.querySelectorAll('.filter-btn');
const visibleCountEl = document.getElementById('visibleCount');
const totalCountEl = document.getElementById('totalCount');
const headerCountEl = document.getElementById('headerCount');

let currentFilter = 'all';
let currentSearch = '';

function renderCards(data) {
    cardsGrid.innerHTML = '';
    data.forEach(item => {
        const card = document.createElement('div');
        card.className = 'card';
        card.dataset.id = item.id;
        card.dataset.category = item.category;
        card.dataset.term = item.term.toLowerCase();
        card.dataset.mode = 'simple';

        const metaHtml = item.meta ? item.meta.map(m => `<span class="meta">${m}</span>`).join('') : '';

        // Обработка academic (массив или строка)
        let academicHtml = '';
        if (Array.isArray(item.academic)) {
            academicHtml = `<ul>${item.academic.map(point => `<li>${point}</li>`).join('')}</ul>`;
        } else {
            academicHtml = item.academic || '';
        }

        card.innerHTML = `
            <div class="card-header">
                <span class="term">${item.term}</span>
                <span class="tag ${item.tagColor}">${item.tag}</span>
                <span class="mode-badge" id="modeBadge_${item.id}">Просто</span>
            </div>
            <div class="definition" id="def_${item.id}">
                <div class="simple-def"><strong>Простыми словами:</strong> ${item.simple || ''}</div>
                <div class="example"><strong>Пример из жизни:</strong> ${item.example || ''}</div>
                <span class="source">${item.source || ''}</span>
            </div>
            <div class="academic-definition" id="acad_${item.id}" style="display: none;">
                <div class="academic-text">
                    <strong>Академическое определение:</strong>
                    ${academicHtml}
                </div>
                <span class="source">${item.source || ''}</span>
            </div>
            <div class="meta-tags">${metaHtml}</div>
            <div class="click-hint">Кликните, чтобы переключить определение</div>
        `;

        // ===== ЛОГИКА КЛИКА (3 клика) =====
        let clickCount = 0;

        card.addEventListener('click', function(e) {
            if (e.target.closest('.filter-btn')) return;

            const simpleDef = this.querySelector('.definition');
            const academicDef = this.querySelector('.academic-definition');
            const badge = this.querySelector('.mode-badge');
            const metaTags = this.querySelector('.meta-tags');
            const clickHint = this.querySelector('.click-hint');

            clickCount++;

            if (clickCount === 1) {
                // 1-й клик: академическое определение
                simpleDef.style.display = 'none';
                academicDef.style.display = 'block';
                badge.textContent = 'Академическое';
                badge.style.background = '#1d3b5c';
                badge.style.color = 'white';
                if (metaTags) metaTags.style.display = 'none';
                if (clickHint) clickHint.style.display = 'none';
                this.classList.add('mode-only-definition');

            } else if (clickCount === 2) {
                // 2-й клик: остаётся только определение (уже в режиме)

            } else if (clickCount === 3) {
                // 3-й клик: возврат к исходному
                simpleDef.style.display = 'block';
                academicDef.style.display = 'none';
                badge.textContent = 'Просто';
                badge.style.background = '#e6edf6';
                badge.style.color = '#1a2a3a';
                if (metaTags) metaTags.style.display = 'flex';
                if (clickHint) clickHint.style.display = 'block';
                this.classList.remove('mode-only-definition');
                clickCount = 0;
            }
        });

        cardsGrid.appendChild(card);
    });

    totalCountEl.textContent = data.length;
    headerCountEl.textContent = data.length;
    updateVisibleCount();
}

function filterAndSearch() {
    const allCards = document.querySelectorAll('.card');
    const searchTerm = currentSearch.toLowerCase().trim();

    allCards.forEach(card => {
        const term = card.dataset.term || '';
        const category = card.dataset.category || '';
        const matchesSearch = searchTerm === '' || term.includes(searchTerm);
        const matchesFilter = currentFilter === 'all' || category === currentFilter;

        if (matchesSearch && matchesFilter) {
            card.classList.remove('hidden');
        } else {
            card.classList.add('hidden');
        }
    });

    updateVisibleCount();
}

function updateVisibleCount() {
    const visible = document.querySelectorAll('.card:not(.hidden)').length;
    visibleCountEl.textContent = visible;
}

// ===== СОБЫТИЯ =====
searchInput.addEventListener('input', function() {
    currentSearch = this.value;
    clearBtn.classList.toggle('visible', this.value.length > 0);
    filterAndSearch();
});

clearBtn.addEventListener('click', function() {
    searchInput.value = '';
    currentSearch = '';
    clearBtn.classList.remove('visible');
    filterAndSearch();
    searchInput.focus();
});

filterBtns.forEach(btn => {
    btn.addEventListener('click', function() {
        filterBtns.forEach(b => b.classList.remove('active'));
        this.classList.add('active');
        currentFilter = this.dataset.filter;
        filterAndSearch();
    });
});

// ===== ГОРЯЧИЕ КЛАВИШИ =====
document.addEventListener('keydown', function(e) {
    if ((e.ctrlKey || e.metaKey) && e.key === 'f') {
        e.preventDefault();
        searchInput.focus();
        searchInput.select();
    }
    if (e.key === 'Escape') {
        if (searchInput.value) {
            searchInput.value = '';
            currentSearch = '';
            clearBtn.classList.remove('visible');
            filterAndSearch();
            searchInput.blur();
        }
    }
});

